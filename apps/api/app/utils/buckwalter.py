"""تحويل ترميز بكوولتر الموسَّع (المدونة القرآنية) إلى العربية.

ترميز تقني قياسي لتمثيل الحروف العربية بمحارف لاتينية، وليس محتوى دينيًا.
تستعمله المدونة القرآنية بجامعة ليدز في أعمدة الصيغة (FORM) والأصل (LEM)
والجذر (ROOT).

**حدّ علمي صارم:** ناتج هذا التحويل لا يُعرض أبدًا بوصفه نصًا قرآنيًا.
نص العرض يأتي حصرًا من إصدار النص الموثق (مشروع تنزيل). التحويل هنا
لتمثيل بيانات صرفية منسوبة لمصدرها: الجذر والأصل وتقريب المقطع.
"""

from __future__ import annotations

# الخريطة الأساسية: محرف واحد ↔ حرف/حركة عربية
BUCKWALTER: dict[str, str] = {
    "'": "ء", "|": "آ", ">": "أ", "&": "ؤ",
    "<": "إ", "}": "ئ", "A": "ا", "b": "ب",
    "p": "ة", "t": "ت", "v": "ث", "j": "ج",
    "H": "ح", "x": "خ", "d": "د", "*": "ذ",
    "r": "ر", "z": "ز", "s": "س", "$": "ش",
    "S": "ص", "D": "ض", "T": "ط", "Z": "ظ",
    "E": "ع", "g": "غ", "_": "ـ", "f": "ف",
    "q": "ق", "k": "ك", "l": "ل", "m": "م",
    "n": "ن", "h": "ه", "w": "و", "Y": "ى",
    "y": "ي", "F": "ً", "N": "ٌ", "K": "ٍ",
    "a": "َ", "u": "ُ", "i": "ِ", "~": "ّ",
    "o": "ْ", "^": "ٓ", "#": "ٔ", "`": "ٰ",
    "{": "ٱ",
}

# علامات ضبط إملائية خاصة بالمدونة (حرف صامت، صلة، إشمام…). هي تعليق على
# الرسم لا حروفًا، وتُسقط في التقريب العربي لأن ربطها بمحارف يونيكود بعينها
# غير موثق في ملف المصدر، وربطها بالتخمين يُدخل خطأً في بيانات معروضة.
QAC_ORTHOGRAPHIC_MARKS = frozenset("@[]!\"%+,-.:;")

# مسافة داخل الصيغة: كلمة واحدة في عدّ المدونة تُرسم بفراغ (إل ياسين 37:130)
_PASSTHROUGH = frozenset(" ")


class BuckwalterError(ValueError):
    """محرف غير معروف في نص بكوولتر — يوقف البناء بدل تمرير بيانات مشوهة."""


def to_arabic(value: str, *, keep_marks: bool = False) -> str:
    """يحوّل نص بكوولتر إلى العربية، ويرفع خطأ عند أي محرف غير معروف.

    keep_marks=False يُسقط علامات الضبط الإملائية الخاصة بالمدونة."""
    out: list[str] = []
    for ch in value:
        if ch in BUCKWALTER:
            out.append(BUCKWALTER[ch])
        elif ch in QAC_ORTHOGRAPHIC_MARKS:
            if keep_marks:
                out.append(ch)
        elif ch in _PASSTHROUGH:
            out.append(ch)
        else:
            raise BuckwalterError(f"محرف بكوولتر غير معروف: {ch!r} في {value!r}")
    return "".join(out)


def split_lemma(lemma_bw: str) -> tuple[str, int | None]:
    """تفصل رقم تمييز المتشابهات في نهاية الأصل (maE2 → maE، 2).

    المدونة تلحق رقمًا بالأصل للتفريق بين أصلين متطابقين رسمًا."""
    if len(lemma_bw) > 1 and lemma_bw[-1].isdigit():
        return lemma_bw[:-1], int(lemma_bw[-1])
    return lemma_bw, None
