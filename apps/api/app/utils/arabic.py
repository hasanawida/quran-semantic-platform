import re
import unicodedata

# =============================================================================
# تطبيع للبحث فقط — لا يستخدم أبدًا على نص العرض القرآني.
#
# نطاقات العلامات المحذوفة:
#   U+0610-061A  علامات قرآنية وعلامات ضبط
#   U+064B-0653  التشكيل الأساسي والمدة (دون الهمزة التركيبية)
#   U+0656-065F  علامات ضبط إضافية
#   U+0670       الألف الخنجرية
#   U+06D6-06ED  علامات الوقف ونهاية الآية والسجدة والحروف الصغيرة
#   U+08D3-08FF  علامات Arabic Extended-A المعتمدة في مصاحف رقمية حديثة
#   U+0640       التطويل (الكشيدة)
#
# تنبيه جوهري: U+0654/U+0655 (الهمزة فوق/تحت الحرف) ليست تشكيلًا؛
# هي همزة — حرف صامت قد يكون من حروف الجذر — وتعالج صراحة قبل الحذف.
# =============================================================================

DIACRITICS = re.compile(
    "[\u0610-\u061A\u064B-\u0653\u0656-\u065F\u0670\u06D6-\u06ED\u08D3-\u08FF\u0640]"
)
WHITESPACE = re.compile(r"\s+")
ROOT_CHARS = re.compile("[^\u0621-\u064A]")

# همزة تركيبية بقيت بعد NFC (على تطويل أو ألف مقصورة ونحوهما، كما في: شيـٔا)
COMBINING_HAMZA = re.compile("[\u0654\u0655]")

# واو بعدها ألف خنجرية ترسم في الإملاء الحديث ألفًا (الصلوٰة → الصلاة)،
# ما لم تتبعها ألف صريحة (نحو الربوٰا)
WAW_DAGGER_ALEF = re.compile("\u0648\u0670(?!\u0627)")

# خريطة البحث النصي: توحيد صور الألف والياء لرفع استرجاع البحث
SEARCH_MAP = str.maketrans(
    {
        "أ": "ا",  # همزة على ألف → ا
        "إ": "ا",  # همزة تحت ألف → ا
        "آ": "ا",  # ألف مدة → ا
        "ٱ": "ا",  # همزة وصل → ا
        "ى": "ي",  # ألف مقصورة → ي
        "ؤ": "و",  # همزة على واو → و
        "ئ": "ي",  # همزة على نبرة → ي
    }
)

# خريطة الجذور: كل صور الهمزة توحد إلى الألف — اصطلاح المدونة القرآنية
# (جامعة ليدز) في تمثيل بنية الجذر: الهمزة ترمز بالألف لأن الألف الخالصة
# لا تكون أصلًا من أصول الجذر أبدًا (الأجوف أصله واو أو ياء)، فلا تصادم:
# سأل = سءل = سؤل → سال، بينما سول وسيل تبقيان كما هما
ROOT_HAMZA_MAP = str.maketrans(
    {
        "ء": "ا",
        "أ": "ا",
        "إ": "ا",
        "آ": "ا",
        "ؤ": "ا",
        "ئ": "ا",
    }
)
ROOT_LETTER_MAP = str.maketrans(
    {
        "ى": "ي",  # ألف مقصورة → ي
        "ٱ": "ا",  # همزة وصل → ا
    }
)


# =============================================================================
# ترميز الكلمات (Tokenization) — سياسة المنصة الموثقة
#
# الكلمة ما حمل حرفًا عربيًا. علامات الوقف المستقلة (ۖ ۗ ۘ …) ورموز نهاية
# الآية تُرسم منفصلة بفراغ لكنها ليست كلمات، فلا تأخذ رقمًا — وهذا يوافق
# ترقيم الكلمات في المدونة القرآنية، فتصح المحاذاة بين النص والتحليل.
#
# التقسيم على الفراغ وحده: لا يُحذف من النص شيء ولا يُعاد تركيبه، وتُحفظ
# مواضع الحروف (char_start/char_end) للرجوع إلى نص الآية الأصلي.
# =============================================================================

WORD_LETTER = re.compile("[ء-يٱ]")


def tokenize_ayah(text: str) -> list[tuple[int, int, str]]:
    """يعيد (بداية، نهاية، نص الكلمة) لكل كلمة تحمل حرفًا عربيًا.

    المواضع فهارس محارف في نص الآية كما هو، فيبقى التمييز مرتبطًا بالنص
    الموثق لا بنسخة معالجة منه."""
    tokens: list[tuple[int, int, str]] = []
    position = 0
    for part in text.split(" "):
        start = position
        position += len(part) + 1  # +1 للفراغ الفاصل
        if WORD_LETTER.search(part):
            tokens.append((start, start + len(part), part))
    return tokens


def count_word_tokens(text: str) -> int:
    """عدد كلمات الآية وفق ترميز المنصة."""
    return len(tokenize_ayah(text))


def normalize_arabic_search(value: str) -> str:
    """تطبيع للبحث فقط — لا يستخدم أبدًا على نص العرض القرآني."""
    value = unicodedata.normalize("NFC", value)
    # الهمزة التركيبية المتبقية بعد NFC تعامل همزةً على نبرة لا تشكيلًا
    value = COMBINING_HAMZA.sub("ئ", value)
    value = WAW_DAGGER_ALEF.sub("ا", value)
    value = DIACRITICS.sub("", value)
    value = value.translate(SEARCH_MAP)
    return WHITESPACE.sub(" ", value).strip()


def normalize_root_input(value: str) -> str:
    """مفتاح قانوني للجذر: الهمزة بكل صورها توحد إلى الألف (اصطلاح المدونة)."""
    value = unicodedata.normalize("NFC", value)
    value = COMBINING_HAMZA.sub("ا", value)
    value = DIACRITICS.sub("", value)
    value = value.translate(ROOT_HAMZA_MAP)
    value = value.translate(ROOT_LETTER_MAP)
    return ROOT_CHARS.sub("", value)


# =============================================================================
# مفتاحان مشتقان للبحث — يُبنيان **فوق** normalize_arabic_search ولا يعدّلانها.
#
# لماذا لا تُعدَّل الدالة الأصل: مخرجها هو Token.normalized_text وعمود
# Ayah.plain_search_text المخزَّن ومفاتيح الاختبارات الذهبية؛ تغييرها يُبطل
# محاذاة الكلمات بالنص ويوجب إعادة بناء بيانات منشورة.
#
# 1) مفتاح الهيكل (normalize_search_skeleton) — علاج مقيس لفرق الرسم:
#    الرسم العثماني يكتب ألف المدّ ألفًا خنجرية (U+0670) وهي محذوفة مع
#    التشكيل، فيصير المخزَّن «العلمين» بينما المستعمل يكتب «العالمين».
#    و4367 آية من 6236 (70%) فيها هذا الحرف، فالمطابقة الصارمة وحدها
#    تعيد صفرًا في: العالمين، الكتاب، السماوات، مالك، الانسان، الظالمين.
#
#    العلاج **متناظر**: يُحذف حرف الألف من طرفي المقارنة معًا (المخزون
#    والطلب)، فلا يحتاج النظام أن يعرف أمكتوبة الألف في الرسم أم خنجرية
#    أم محذوفة. ولا تُستعمل قاعدة «الخنجرية ← ألف» الساذجة: تُصلح حالات
#    وتكسر ما يعمل اليوم (ذلك تصير «ذالك» فيسقط طلبها، وهذا تصير «هاذا»).
#
#    وحدّ الطول (MIN_SKELETON_LENGTH في خدمة القرآن) شرط عملي: مفتاح من
#    حرفين يفيض ضجيجًا — طلب «إله» مفتاحه «له» فيطابق 2687 آية مقابل 191
#    بالمطابقة الصارمة.
#
# 2) مفتاح اسم السورة (normalize_surah_name): الأسماء المخزَّنة غير موحَّدة
#    في رسم الهمزة («ابراهيم» بلا همزة و«الإسراء» بها، و«سبإ» و«النبإ»
#    بهمزة أخيرة)، والمستعمل يكتب «الفاتحه» بالهاء. فيوحَّد الطرفان
#    وتُسقط «ال» التعريف من أولهما.
#
# كلاهما **للمطابقة فقط**: لا يُخزَّنان في القاعدة ولا يُعرضان للمستعمل
# ولا يمسّان نص العرض (Ayah.uthmani_text و Surah.arabic_name).
# =============================================================================

# التاء المربوطة والهاء لا يفرق بينهما كاتب الطلب («البقره» و«البقرة»)
TA_MARBUTA_TO_HA = str.maketrans({"ة": "ه"})

# الألف والهمزة المفردة — الحرفان اللذان يختلف رسمهما بين المصحف والإملاء
SKELETON_DROP = re.compile("[اء]")

# «ال» التعريف في أول الاسم متبوعةً بحرف — فلا تُمسّ «ال عمران» (بعدها فراغ)
DEFINITE_ARTICLE = re.compile("^ال(?=\\S)")


def normalize_search_skeleton(value: str) -> str:
    """مفتاح المطابقة التقريبية — للبحث فقط، ولا يُعرض نصًّا أبدًا.

    **عقد ملزم:** يجب أن يبقى مطابقًا حرفًا بحرف لتعبير SQL في
    `QuranService._skeleton_expr()` المطبَّق على `Ayah.plain_search_text`.
    أي فرق بينهما يعني بحثًا يعيد صفرًا صامتًا بلا رسالة خطأ — ولذلك
    يحرسه `test_skeleton_key_matches_its_sql_counterpart`."""
    value = normalize_arabic_search(value).translate(TA_MARBUTA_TO_HA)
    return SKELETON_DROP.sub("", value)


def normalize_surah_name(value: str) -> str:
    """مفتاح مطابقة اسم السورة — لا يمسّ `Surah.arabic_name` المعروض."""
    value = normalize_arabic_search(value).translate(TA_MARBUTA_TO_HA)
    return DEFINITE_ARTICLE.sub("", value)
